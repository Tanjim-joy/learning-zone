 **মডিউল ১: ভূমিকা ও গাণিতিক ভিত্তি (Foundations)** সম্পর্কিত বিস্তারিত আলোচনা নিচে প্রদান করা হলো:

এই মডিউলটি কম্পিউটার বিজ্ঞানের মূল ভিত্তি স্থাপন করে, যেখানে অ্যালগরিদম কী, এটি কীভাবে পরিমাপ করা হয় এবং রিকার্শনের মৌলিক নিয়মগুলো শেখানো হয়।

### ১. অ্যালগরিদমের সূচনা (Introduction to Algorithms)
*   **অ্যালগরিদম:** এটি হলো কোনো নির্দিষ্ট লক্ষ্য অর্জনের জন্য ডেটার ওপর পরিচালিত নির্দেশনার একটি সুনির্দিষ্ট ক্রম [২৮৭, ৬১১]। এটি মূলত সমস্যা সমাধানের একটি ধাপ-ভিত্তিক তালিকা [২৯০, ৮১০]।
*   **সমস্যা বনাম ইনস্ট্যান্স (Problem vs. Instance):** কম্পিউটার বিজ্ঞানে 'সর্টিং' (সাজানো) একটি সাধারণ **সমস্যা** [৭, ১৪৫]। কিন্তু যখন আপনি একটি নির্দিষ্ট তালিকার (যেমন: {১৫৪, ২৪৫, ১৩৩৭}) কথা বলেন, তখন সেটিকে বলা হয় ওই সমস্যার একটি **ইনস্ট্যান্স** বা উদাহরণ [৮, ১৪৬]।

### ২. অ্যালগরিদমিক জটিলতা (Algorithmic Complexity)
অ্যালগরিদমের দক্ষতা পরিমাপের জন্য আমরা অ্যাসিম্পটোটিক নোটেশন (Asymptotic Notation) ব্যবহার করি, যা ইনপুট ডেটার পরিমাণ বাড়লে প্রোগ্রামের মেমরি ও সময়ের ব্যবহার কীভাবে বাড়ে তা প্রকাশ করে [২৮১, ৬৭৮]।
*   **Big-O Notation:** এটি অ্যালগরিদমের সময়ের **সর্বোচ্চ সীমা (Upper Bound)** প্রকাশ করে [১২, ২০, ৩০১]। যেমন: $O(n)$ মানে ইনপুট বাড়লে সময় রৈখিকভাবে বাড়বে।
*   **Big-Theta (Θ) Notation:** এটি একটি **সুনির্দিষ্ট সীমা (Tight Bound)** যা একই সাথে সর্বোচ্চ ও সর্বনিম্ন সীমা নির্দেশ করে [১২, ৩০৭]।
*   **Big-Omega (Ω) Notation:** এটি অ্যালগরিদমের সময়ের **সর্বনিম্ন সীমা (Lower Bound)** প্রকাশ করে [১৮, ৩০৬]।
*   **স্কেলেবিলিটি (Scalability):** একটি অ্যালগরিদম বড় আকারের ডেটার ক্ষেত্রে কতটা কার্যকর হবে, তা-ই এর স্কেলেবিলিটি [২৯১]।

### ৩. রিকার্শন (Recursion)
রিকার্শন হলো এমন একটি পদ্ধতি যেখানে একটি বড় সমস্যাকে ছোট ছোট একই ধরণের উপ-সমস্যায় ভাগ করে সমাধান করা হয় [৩১০, ৭৫৪]। সাধারণত একটি ফাংশন যখন নিজেকেই বারবার কল করে, তখন তাকে রিকার্সিভ ফাংশন বলা হয় [৩১৪, ৭৫৭]।

**রিকার্শনের তিনটি গুরুত্বপূর্ণ আইন [৭৫৮]:**
১. একটি **বেস কেস (Base Case)** থাকতে হবে, যা রিকার্শন থামিয়ে দেয় [৭৫৮]।
২. অ্যালগরিদমকে অবশ্যই তার অবস্থা পরিবর্তন করে বেস কেসের দিকে এগিয়ে যেতে হবে [৭৫৮]।
৩. ফাংশনটিকে অবশ্যই নিজেকে পুনরায় কল করতে হবে [৭৫৮]।

*   **রানটাইম স্ট্যাক (Runtime Stack):** যখনই একটি রিকার্সিভ ফাংশন কল করা হয়, তখন কম্পিউটারের মেমরিতে একটি **স্ট্যাক ফ্রেম (Stack Frame)** তৈরি হয় যা ওই ফাংশনের লোকাল ভ্যারিয়েবল ও তথ্য জমা রাখে [৩২৯, ৭৬৮]।

