অধ্যায় ৬: সার্চিং অ্যালগরিদম (Searching Algorithms)
অনুসন্ধান বা সার্চিং হলো একটি ডাটা সংগ্রহের মধ্য থেকে কোনো নির্দিষ্ট তথ্য খুঁজে বের করার প্রক্রিয়া। এর প্রধান দুটি পদ্ধতি হলো:

১. লিনিয়ার সার্চ(Linear Search):
    পদ্ধতি: এটি সবচেয়ে সহজ পদ্ধতি যেখানে তালিকার শুরু থেকে শেষ পর্যন্ত প্রতিটি উপাদান একে একে চেক করা হয় যতক্ষণ না কাঙ্ক্ষিত তথ্যটি পাওয়া যায়। 
    এটি অনেকটা বইয়ের স্তূপ থেকে একটি নির্দিষ্ট বই খুঁজে বের করার মতো।

    সময় জটিলতা(Complexity):
        এর গড় এবং ওরস্ট - কেস সময় জটিলতা হলো O(n), কারণ তথ্যের পরিমাণ বাড়লে অনুসন্ধানের ধাপও সমানুপাতিকভাবে বাড়ে । 
        তবে বেস্ট কেসে যদি প্রথমবারেই তথ্য পাওয়া যায় তবে তা O(1)।

২. বাইনারি সার্চ(Binary Search):
    শর্ত: এই অ্যালগরিদমটি কাজ করার জন্য ডাটা অবশ্যই সর্টেড (Sorted) বা সাজানো থাকতে হবে ।
    পদ্ধতি: এটি 'ডিভাইড অ্যান্ড কনকার'(Divide and Conquer) নীতিতে কাজ করে । প্রতিবার অনুসন্ধানে এটি তালিকার মাঝখানের মানের সাথে তুলনা করে এবং সার্চ এরিয়া অর্ধেক করে ফেলে।
    সময় জটিলতা: এর ওরস্ট - কেস সময় জটিলতা অত্যন্ত দক্ষ, যা হলো O(\log n)। যেমন—১,০০০ উপাদানের একটি তালিকায় লিনিয়ার সার্চে ১,০০০ বার চেক করতে হতে পারে, 
    কিন্তু বাইনারি সার্চে মাত্র ১০টি তুলনা যথেষ্ট।

অধ্যায় ৭: হ্যাশ টেবিল (Hash Tables)

হ্যাশ টেবিল হলো এমন একটি ডাটা স্ট্রাকচার যা গড়ে O(1) বা ধ্রুবক সময়ে তথ্য খুঁজে পেতে সাহায্য করে।

১. হ্যাশ ফাংশন(Hash Function):
সংজ্ঞা: এটি একটি গাণিতিক ফাংশন যা বড় কোনো 'কী' (Key) গ্রহণ করে সেটিকে একটি নির্দিষ্ট সীমার মধ্যে ছোট ইন্টিজার ইনডেক্সে রূপান্তর করে।       
বৈশিষ্ট্য: একটি ভালো হ্যাশ ফাংশন দ্রুত গণনাযোগ্য হয় এবং ডাটাগুলোকে টেবিলের সব জায়গায় সমানভাবে ছড়িয়ে দেয় (Uniform distribution) । 
সাধারণ একটি পদ্ধতি হলো 'রিমাইন্ডার মেথড' বা মডুলো অপারেশন (Key % TableSize) ।

২. কলিশন রেজোলিউশন (Collision Resolution):
যখন দুটি ভিন্ন 'কী' হ্যাশ ফাংশনের মাধ্যমে একই ইনডেক্স বা স্লট নির্দেশ করে, তখন তাকে কলিশন (Collision) বা সংঘর্ষ বলা হয়। এটি সমাধানের দুটি প্রধান পদ্ধতি আছে:

*   ওপেন অ্যাড্রেসিং (Open Addressing): যদি নির্দিষ্ট স্লটটি পূর্ণ থাকে, তবে টেবিলের অন্য কোনো খালি স্লট খুঁজে সেখানে ডাটা রাখা হয়। এর কয়েকটি ধরন হলো:
    *   লিনিয়ার প্রোবিং (Linear Probing): ক্রমান্বয়ে পরবর্তী স্লটগুলো (+১) চেক করা হয় [১১০, ৩৬৯, ৫৫৪, ৭৭০]। এটি 'ক্লাস্টারিং' বা ডাটা এক জায়গায় জমা হওয়ার সমস্যা তৈরি করতে পারে।
    *   কোয়াড্রেটিক প্রোবিং (Quadratic Probing): খালি স্লট খোঁজার জন্য বর্গীয় ব্যবধান (যেমন: ১, ৪, ৯...) ব্যবহার করা হয় ।
    *   ডাবল হ্যাশিং (Double Hashing): প্রথমবার কলিশন হলে দ্বিতীয় আরেকটি হ্যাশ ফাংশন ব্যবহার করে পরবর্তী স্লটের দূরত্ব নির্ধারণ করা হয় ।

*   চেইনিং (Chaining/Separate Chaining): এখানে হ্যাশ টেবিলের প্রতিটি স্লট একটি লিঙ্কড লিস্ট (Linked List) ধারণ করে [১০৯, ৪০১, ৫৪৯, ৭৭৬]। যদি একাধিক ডাটা একই ইনডেক্সে ম্যাপ করে, তবে তারা ওই ইনডেক্সের লিস্টে যুক্ত হতে থাকে [৪০১, ৭৭৬]। এটি ইমপ্লিমেন্ট করা সহজ এবং এতে টেবিল কখনোই পুরোপুরি 'ফুল' হয় না [৪০৩, ৪০৫, ৪১৩]।

সারসংক্ষেপ: হ্যাশ টেবিল ব্যবহারের মূল সুবিধা হলো এর গতি, তবে মেমরি ব্যবহার এবং কলিশন ব্যবস্থাপনার ক্ষেত্রে কিছু ট্রেড-অফ বা আপস করতে হয় । 

